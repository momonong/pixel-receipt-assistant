#!/usr/bin/env python3
"""Build the offline preview from its canonical fragment and local icon subset."""

from __future__ import annotations

import argparse
from pathlib import Path


DIRECTORY = Path(__file__).resolve().parent


def render() -> str:
    fragment = (DIRECTORY / "receipt-actions.fragment.html").read_text(encoding="utf-8")
    icons = (DIRECTORY / "lucide-subset.js").read_text(encoding="utf-8")
    license_text = (DIRECTORY / "LUCIDE-LICENSE.txt").read_text(encoding="utf-8")
    if "</script" in icons.lower() or "-->" in license_text:
        raise ValueError("Icon source or license contains an unsafe HTML delimiter")
    return """<!doctype html>
<html lang="zh-Hant">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="light dark">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; base-uri 'none'; form-action 'none'">
  <title>PixelReceipt｜收據操作預覽</title>
  <!-- Generated by build_preview.py. Edit receipt-actions.fragment.html instead. -->
  <style>
    html { color-scheme: light dark; }
    body { margin: 0; background: light-dark(#FAFBFB, #101211); }
    .viz-dotted-background {
      background-image: radial-gradient(light-dark(#D4DCDA, #35413C) 0.8px, transparent 0.8px);
      background-size: 16px 16px;
    }
  </style>
</head>
<body>
<!--
Lucide 1.8.0 icon subset license:
""" + license_text.rstrip() + """
-->
<script>
""" + icons.rstrip() + """
</script>
<main>
""" + fragment.rstrip() + """
</main>
</body>
</html>
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that index.html matches the sources")
    args = parser.parse_args()
    destination = DIRECTORY / "index.html"
    result = render()
    if args.check:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != result:
            parser.exit(1, "index.html is out of date; run build_preview.py\n")
        print("index.html matches its sources")
    else:
        destination.write_text(result, encoding="utf-8")
        print("Built index.html")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
